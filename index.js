/*Теоретическая часть

Побитовые операторы работают с числом как с набором из 32 бит. 
Перед операцией число приводится к 32-битному целому со знаком, а результат возвращается обычным числом.

Оператор	    Название	        Правило	                           
&	               И	            1, если бит 1 в обоих числах	       
\|	              ИЛИ	            1, если бит 1 хотя бы в одном	
^	              XOR	            1, если биты различаются
~	               НЕ	            инвертирует все биты
<<	          Сдвиг влево	        заполняет справа нулями
>>	      Сдвиг вправо со знаком	сохраняет знак числа
>>>       Сдвиг вправо с нулями	    заполняет слева нулями

Операторы с более высоким приоритетом выполняются раньше, и их результат становится операндом для операторов с низким приоритетом. 
Выполнение по приоритетам:
1. ~
2. <<, >>, >>>
3. &
4. ^
5. |

Шаблонные литералы

console.log("2" > 1); // true, строка преобразуется в число
Если сравнить или сложить значения разных типов, JavaScript сам превратит одно в другое
"2" > 1 строка "2" превращается в число 2. Потому 2 > 1 и результат true.
*/

const secondsInMinute = 60;
const minutesInHour = 60;

const secondsInHour = secondsInMinute * minutesInHour;
console.log(`В часе ${secondsInHour} секунд.`);



let variable = 0;
// Увеличиваем значение на 7: 0 + 7 = 7
variable += 7;
// Увеличиваем значение в 4 раза: 7 * 4 = 28
variable *= 4;
// Уменьшаем значение на 8: 28 - 8 = 20
variable -= 8;
// Делим значение на 4: 20 / 4 = 5
variable /= 4;
// Возводим значение в 3 степень: 5 ** 3 = 125
variable **= 3;
// Находим остаток от деления на 5: 125 % 5 = 0
variable %= 5;
// Выводим итоговое значение
console.log(`Итоговое значение переменной: ${variable}`);


// Сравнение чисел
console.log(5 > 4); // true
// Строки сравниваются посимвольно по кодам Unicode:
// "а" (U+0430) меньше "я" (U+044F), поэтому "ананас" не больше "яблоко"
console.log("ананас" > "яблоко"); // false
// Сравниваются строки, а не числа: сравнение идёт по первому символу,
// "2" (код 50) больше "1" (код 49)
console.log("2" > "12"); // true
// Нестрогое равенство: undefined и null считаются равными
console.log(undefined == null); // true
// Строгое равенство сравнивает ещё и тип, а типы разные
console.log(undefined === null); // false
// null при нестрогом сравнении с строкой не приводится к числу,
// поэтому равенства нет
console.log(null == "0"); // false
// +"0" превращает строку в число 0, но null это не число, типы разные
console.log(null === +"0"); // false



// Дополнительное задание
const a = 5; // в двоичной системе 101
const b = 3; // в двоичной системе 011
// Побитовое И: бит равен 1, только если он 1 в обоих числах
// 101 & 011 = 001
console.log(a & b); // 1
// Побитовое ИЛИ: бит равен 1, если он 1 хотя бы в одном числе
// 101 | 011 = 111
console.log(a | b); // 7
// Исключающее ИЛИ (XOR): бит равен 1, если биты в числах разные
// 101 ^ 011 = 110
console.log(a ^ b); // 6
// Побитовое НЕ: инвертирует все биты, результат равен -(a + 1)
console.log(~a); // -6
// Сдвиг влево на 1 бит равен умножению на 2
// 101 << 1 = 1010
console.log(a << 1); // 10
// Сдвиг вправо на 1 бит равен целочисленному делению на 2
// 011 >> 1 = 001
console.log(b >> 1); // 1

// Приоритет операторов

// Умножение имеет более высокий приоритет, чем сложение:
// сначала 3 * 4 = 12, потом 2 + 12
console.log(2 + 3 * 4); // 14
// Скобки меняют порядок: сначала 2 + 3 = 5, потом 5 * 4
console.log((2 + 3) * 4); // 20